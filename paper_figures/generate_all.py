"""Generate all paper figures in batch."""

from __future__ import annotations

import sys
import time
from pathlib import Path

# Add project root to path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

# Import all figure generators
from generators.fig_version_evolution import create_timeline_figure
from generators.fig_stability_domain import create_stability_heatmap
from generators.fig_energy_analysis import create_energy_analysis_figure
from generators.fig_phase_portrait import create_phase_portrait
from generators.fig_hardware_specs import create_hardware_specs_figure

OUTPUT_DIR = Path(__file__).resolve().parent / "output"


def generate_all_figures():
    """Generate all paper figures."""
    print("=" * 60)
    print("Generating Paper Figures for HW-1 Project")
    print("=" * 60)

    figures = [
        ("Figure 1: Version Evolution Timeline", create_timeline_figure),
        ("Figure 2: Stability Domain Heatmap", create_stability_heatmap),
        ("Figure 3: Energy Analysis", create_energy_analysis_figure),
        ("Figure 4: Phase Portrait", create_phase_portrait),
        ("Figure 5: Hardware Specifications", create_hardware_specs_figure),
    ]

    generated_files = []

    for i, (title, generator_func) in enumerate(figures, 1):
        print(f"\n[{i}/{len(figures)}] Generating {title}...")
        start_time = time.time()

        try:
            result_path = generator_func()
            elapsed = time.time() - start_time
            print(f"    [OK] Completed in {elapsed:.2f}s")
            generated_files.append(result_path)
        except Exception as e:
            print(f"    [ERROR] {e}")
            import traceback

            traceback.print_exc()

    print("\n" + "=" * 60)
    print(f"Generation Complete: {len(generated_files)}/{len(figures)} figures")
    print("=" * 60)

    print(f"\nOutput directory: {OUTPUT_DIR}")
    print("\nGenerated files:")
    for fmt in ["svg", "pdf", "png"]:
        print(f"\n  {fmt.upper()} files:")
        fmt_files = list(OUTPUT_DIR.glob(f"*.{fmt}"))
        for f in sorted(fmt_files):
            print(f"    - {f.name}")

    return generated_files


