OUTPUT_DIR = Path(__file__).resolve().parent / "output"


def generate_all_figures():
    """Generate all paper figures including enhanced versions."""
    print("=" * 70)
    print("HW-1 Enhanced Paper Figures Generation System")
    print("=" * 70)

    figures = [
        # Original 5 figures
        ("Figure 1: Version Evolution Timeline", create_timeline_figure),
        ("Figure 2: Stability Domain Heatmap", create_stability_heatmap),
        ("Figure 3: Energy Analysis", create_energy_analysis_figure),
        ("Figure 4: Phase Portrait", create_phase_portrait),
        ("Figure 5: Hardware Specifications", create_hardware_specs_figure),
        # New enhanced figures
        (
            "Figure 6: Friction Compensation Analysis (V13.7/V16)",
            create_friction_compensation_figure,
        ),
        ("Figure 7: State Estimation Robustness (V17)", create_state_estimation_figure),
        ("Figure 8: 3D Failure Analysis (V18-V20)", create_3d_failure_analysis_figure),
        ("Figure 9: Poincaré Convergence (V5)", create_poincare_convergence_figure),
    ]

    generated_files = []
    failed_figures = []

    for i, (title, generator_func) in enumerate(figures, 1):
        print(f"\n[{i}/{len(figures)}] Generating {title}...")
        start_time = time.time()

        try:
            result_path = generator_func()
            elapsed = time.time() - start_time
            print(f"    [OK] Completed in {elapsed:.2f}s")
            generated_files.append(result_path)
        except Exception as e:
            elapsed = time.time() - start_time
            print(f"    [ERROR] in {elapsed:.2f}s: {e}")
            failed_figures.append((title, str(e)))
            import traceback

            traceback.print_exc()

    print("\n" + "=" * 70)
    print(f"Generation Complete: {len(generated_files)}/{len(figures)} figures")
    print("=" * 70)

    if failed_figures:
        print(f"\n[WARNING] {len(failed_figures)} figure(s) failed:")
        for title, error in failed_figures:
            print(f"  - {title}: {error}")

    print(f"\n[OUTPUT] Directory: {OUTPUT_DIR}")
    print("\n[FILES] Generated files by format:")
    for fmt in ["svg", "pdf", "png"]:
        fmt_files = list(OUTPUT_DIR.glob(f"*.{fmt}"))
        print(f"\n  {fmt.upper()} ({len(fmt_files)} files):")
        for f in sorted(fmt_files):
            size_mb = f.stat().st_size / (1024 * 1024)
            print(f"    - {f.name} ({size_mb:.2f} MB)")

    return generated_files


