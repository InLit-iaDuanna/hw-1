# Git Hooks 安装脚本
# 使用方法: .\ci\install_hooks.ps1

param(
    [switch]$Force  # 强制覆盖已存在的 hooks
)

$ErrorActionPreference = "Stop"

# 项目根目录
if ($PSScriptRoot) {
    $PROJECT_ROOT = Split-Path -Parent $PSScriptRoot
} else {
    $PROJECT_ROOT = "D:\Dunna\Documents\hw-1"
}
Set-Location $PROJECT_ROOT

$HOOKS_DIR = ".git\hooks"

Write-Host "=" * 80 -ForegroundColor Cyan
Write-Host "INSTALLING GIT HOOKS" -ForegroundColor Cyan
Write-Host "=" * 80 -ForegroundColor Cyan
Write-Host ""

# 检查是否为 Git 仓库
if (-not (Test-Path ".git")) {
    Write-Error "Not a git repository. Run 'git init' first."
    exit 1
}

# 确保 hooks 目录存在
if (-not (Test-Path $HOOKS_DIR)) {
    New-Item -ItemType Directory -Path $HOOKS_DIR -Force | Out-Null
}

# Pre-commit hook
$PRE_COMMIT_PATH = "$HOOKS_DIR\pre-commit"
$PRE_COMMIT_CONTENT = @'
#!/bin/sh
# Pre-commit hook for hw-1 project
# Auto-generated by ci/install_hooks.ps1

echo "Running pre-commit checks..."

# 运行代码格式化和 linting
powershell.exe -NoProfile -ExecutionPolicy Bypass -Command "& '.\ci\run_quality.ps1' -Fix"

if [ $? -ne 0 ]; then
    echo "Pre-commit quality check failed. Please fix the issues and try again."
    echo "To skip this check, use: git commit --no-verify"
    exit 1
fi

echo "Pre-commit checks passed!"
exit 0
'@

if ((Test-Path $PRE_COMMIT_PATH) -and -not $Force) {
    Write-Host "⚠ Pre-commit hook already exists. Use -Force to overwrite." -ForegroundColor Yellow
} else {
    $PRE_COMMIT_CONTENT | Out-File -FilePath $PRE_COMMIT_PATH -Encoding ascii -NoNewline
    Write-Host "✓ Installed pre-commit hook" -ForegroundColor Green
}

# Pre-push hook
$PRE_PUSH_PATH = "$HOOKS_DIR\pre-push"
$PRE_PUSH_CONTENT = @'
#!/bin/sh
# Pre-push hook for hw-1 project
# Auto-generated by ci/install_hooks.ps1

echo "Running pre-push checks..."

# 运行测试套件
powershell.exe -NoProfile -ExecutionPolicy Bypass -Command "& '.\ci\run_tests.ps1' -Markers 'unit'"

if [ $? -ne 0 ]; then
    echo "Pre-push tests failed. Please fix the issues and try again."
    echo "To skip this check, use: git push --no-verify"
    exit 1
fi

echo "Pre-push checks passed!"
exit 0
'@

if ((Test-Path $PRE_PUSH_PATH) -and -not $Force) {
    Write-Host "⚠ Pre-push hook already exists. Use -Force to overwrite." -ForegroundColor Yellow
} else {
    $PRE_PUSH_CONTENT | Out-File -FilePath $PRE_PUSH_PATH -Encoding ascii -NoNewline
    Write-Host "✓ Installed pre-push hook" -ForegroundColor Green
}

# Commit-msg hook (可选 - 强制 commit message 格式)
$COMMIT_MSG_PATH = "$HOOKS_DIR\commit-msg"
$COMMIT_MSG_CONTENT = @'
#!/bin/sh
# Commit-msg hook for hw-1 project
# Auto-generated by ci/install_hooks.ps1

commit_msg_file=$1
commit_msg=$(cat "$commit_msg_file")

# 检查 commit message 格式（至少 10 个字符）
if [ ${#commit_msg} -lt 10 ]; then
    echo "Error: Commit message too short (minimum 10 characters)"
    echo "Current message: $commit_msg"
    exit 1
fi

# 可选：检查是否包含问题编号
# if ! echo "$commit_msg" | grep -qE "#[0-9]+"; then
#     echo "Warning: Commit message should reference an issue number (#123)"
# fi

exit 0
'@

if ((Test-Path $COMMIT_MSG_PATH) -and -not $Force) {
    Write-Host "⚠ Commit-msg hook already exists. Use -Force to overwrite." -ForegroundColor Yellow
} else {
    $COMMIT_MSG_CONTENT | Out-File -FilePath $COMMIT_MSG_PATH -Encoding ascii -NoNewline
    Write-Host "✓ Installed commit-msg hook" -ForegroundColor Green
}

Write-Host ""
Write-Host "=" * 80 -ForegroundColor Cyan
Write-Host "GIT HOOKS INSTALLED SUCCESSFULLY" -ForegroundColor Green
Write-Host "=" * 80 -ForegroundColor Cyan
Write-Host ""
Write-Host "Installed hooks:" -ForegroundColor Yellow
Write-Host "  - pre-commit: Runs code quality checks (black, ruff)" -ForegroundColor White
Write-Host "  - pre-push: Runs unit tests" -ForegroundColor White
Write-Host "  - commit-msg: Validates commit message format" -ForegroundColor White
Write-Host ""
Write-Host "To bypass hooks (not recommended):" -ForegroundColor Yellow
Write-Host "  git commit --no-verify" -ForegroundColor White
Write-Host "  git push --no-verify" -ForegroundColor White
Write-Host ""
Write-Host "To uninstall hooks:" -ForegroundColor Yellow
Write-Host "  Remove-Item .git\hooks\pre-commit" -ForegroundColor White
Write-Host "  Remove-Item .git\hooks\pre-push" -ForegroundColor White
Write-Host "  Remove-Item .git\hooks\commit-msg" -ForegroundColor White
Write-Host ""

exit 0
