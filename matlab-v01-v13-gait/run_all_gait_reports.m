%% Run MATLAB reports for V1-V13 gait datasets
% Unified MATLAB export for time-series, energy, and parameter atlas reports.
clear; close all; clc;

cfgs = gait_version_configs();
results = repmat(struct( ...
    'version', "", ...
    'title', "", ...
    'kind', "", ...
    'rows', 0, ...
    'columns', 0, ...
    'hasTime', false, ...
    'hasHipX', false, ...
    'hasContacts', false, ...
    'matFile', "", ...
    'reportFile', ""), 1, numel(cfgs));

for i = 1:numel(cfgs)
    fprintf('\n[%s] %s\n', cfgs(i).id, cfgs(i).title);
    results(i) = run_single_gait_report(cfgs(i));
end

outDir = fullfile(fileparts(mfilename('fullpath')), 'out');
summaryTable = struct2table(results);
writetable(summaryTable, fullfile(outDir, 'v01_v13_matlab_summary.csv'));

fprintf('\nDone. Summary: %s\n', fullfile(outDir, 'v01_v13_matlab_summary.csv'));
