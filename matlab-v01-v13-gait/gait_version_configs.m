function cfg = makeCfg(id, titleText, note, kind, repoRoot, folder, csvRel, jsonRel)
cfg.id = id;
cfg.title = titleText;
cfg.note = note;
cfg.kind = kind;
cfg.folder = folder;
cfg.dataCsv = fullfile(repoRoot, folder, csvRel);
cfg.paramsJson = fullfile(repoRoot, folder, jsonRel);
end
